"""Generate TypeScript types from the backend's pydantic models.

python scripts/gen_types.py            # write the file
python scripts/gen_types.py --check    # exit 1 if it is out of date (CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from wingman.events import EVENTS, ProviderInfo  # noqa: E402
from wingman.runtime import RuntimeConfig, RuntimeUpdate  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "frontend" / "src" / "renderer" / "types" / "generated.ts"
MODELS = [ProviderInfo, *EVENTS.values(), RuntimeConfig, RuntimeUpdate]


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return repr(schema["const"]).replace("'", '"')
    if "enum" in schema:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(s) for s in schema["anyOf"]))
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(schema.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        extra = schema.get("additionalProperties")
        return f"Record<string, {ts_type(extra)}>" if isinstance(extra, dict) else "Record<string, unknown>"
    return "unknown"


def interface(name: str, schema: dict) -> str:
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, sub in schema.get("properties", {}).items():
        optional = "" if prop in required else "?"
        lines.append(f"  {prop}{optional}: {ts_type(sub)}")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    blocks: dict[str, str] = {}
    for model in MODELS:
        schema = model.model_json_schema(mode="serialization")
        for name, sub in schema.get("$defs", {}).items():
            blocks.setdefault(name, interface(name, sub))
        blocks[model.__name__] = interface(model.__name__, schema)
    events = "\n".join(f"  {name}: {model.__name__}" for name, model in EVENTS.items())
    return (
        "// AUTO-GENERATED by backend/scripts/gen_types.py - do not edit by hand.\n"
        "// Run `python backend/scripts/gen_types.py` after changing backend models.\n\n"
        + "\n\n".join(blocks.values())
        + f"\n\nexport interface ServerEvents {{\n{events}\n}}\n"
    )


if __name__ == "__main__":
    content = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != content:
            print(f"{OUT} is out of date. Run: python backend/scripts/gen_types.py")
            sys.exit(1)
        print("generated types are up to date")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(content)
        print(f"wrote {OUT}")
